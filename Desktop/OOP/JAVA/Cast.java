public class Cast {
    public static void main(String[] args) {
        int x=5;
        double y=10.5;
        double tod=x;
        long tol=x;
        float tof=x;
        float tof2=tol;
        int toi=(int)y;
        long tol2=(long)y;
        System.out.println(tod);
        System.out.println(tol);
        System.out.println(tof);
        System.out.println(tof2);
        System.out.println(toi);
        System.out.println(tol2);
    }
    
}
